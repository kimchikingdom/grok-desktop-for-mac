#!/usr/bin/env node
/**
 * Generates the macOS menu-bar template icons without pulling in an image
 * library. Template images are black + alpha only; macOS tints them for light
 * and dark menu bars automatically.
 *
 * Run: node scripts/make-tray-icons.mjs
 */
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const outDir = fileURLToPath(new URL('../apps/desktop/build/', import.meta.url));

/** Menu-bar template: an orbital ring around a solid core. */
function alphaAt(x, y, size) {
  const u = (x + 0.5) / size;
  const v = (y + 0.5) / size;
  const r = Math.hypot(u - 0.5, v - 0.5);
  const edge = 0.9 / size;

  const ringMid = 0.3;
  const ringHalf = 0.07;
  const core = 0.095;

  const ringDelta = Math.abs(r - ringMid);
  let alpha = 0;
  if (ringDelta <= ringHalf - edge) alpha = 255;
  else if (ringDelta < ringHalf + edge) {
    alpha = Math.round(255 * (1 - (ringDelta - (ringHalf - edge)) / (2 * edge)));
  }

  if (r <= core - edge) alpha = 255;
  else if (r < core + edge) {
    alpha = Math.max(alpha, Math.round(255 * (1 - (r - (core - edge)) / (2 * edge))));
  }
  return alpha;
}

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) {
      crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function makePng(size) {
  // RGBA scanlines, each prefixed with filter type 0.
  const raw = Buffer.alloc(size * (size * 4 + 1));
  let offset = 0;
  for (let y = 0; y < size; y += 1) {
    raw[offset] = 0;
    offset += 1;
    for (let x = 0; x < size; x += 1) {
      raw[offset] = 0;
      raw[offset + 1] = 0;
      raw[offset + 2] = 0;
      raw[offset + 3] = alphaAt(x, y, size);
      offset += 4;
    }
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type: RGBA
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

mkdirSync(outDir, { recursive: true });
const encoded = {};
for (const [name, size, key] of [
  ['trayTemplate.png', 16, 'x1'],
  ['trayTemplate@2x.png', 32, 'x2'],
]) {
  const png = makePng(size);
  const file = path.join(outDir, name);
  writeFileSync(file, png);
  encoded[key] = png.toString('base64');
  console.log(`wrote ${file}`);
}

// Embedded as data URLs so the packaged app needs no extra resource files.
const module = `// Generated by scripts/make-tray-icons.mjs — do not edit by hand.
export const TRAY_ICON_1X = 'data:image/png;base64,${encoded.x1}';
export const TRAY_ICON_2X = 'data:image/png;base64,${encoded.x2}';
`;
const modulePath = fileURLToPath(new URL('../apps/desktop/src/main/tray-icon.ts', import.meta.url));
writeFileSync(modulePath, module);
console.log(`wrote ${modulePath}`);
